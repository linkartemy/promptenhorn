// Walk a bot ~60 blocks with pathfinder and report time / stuck recoveries.
import { createRequire } from 'node:module';
import { makeBot, rcon, log, sleep, walkTo } from './common.mjs';
const require = createRequire(import.meta.url);
const { pathfinder, Movements, goals } = require('mineflayer-pathfinder');
const [dx = 0, dz = 60] = process.argv.slice(2).map(Number);
const r = await rcon();
const bot = await makeBot('Walker');
bot.loadPlugin(pathfinder);
const sp = bot.spawnPoint;
await r.command(`tp Walker ${sp.x + 0.5} ${sp.y} ${sp.z + 0.5}`);
await sleep(1500);
const s = bot.entity.position.clone();
const m = new Movements(bot);
m.canDig = false;
bot.pathfinder.setMovements(m);
const t0 = Date.now();
const res = await walkTo(bot, new goals.GoalNearXZ(s.x + dx, s.z + dz, 2), { timeout: 90000 });
log('result', JSON.stringify(res), 'in', (Date.now() - t0) / 1000, 's, moved', bot.entity.position.distanceTo(s).toFixed(1), 'stuck recoveries', bot.walkStuckCount ?? 0);
bot.quit(); r.close(); process.exit(0);
